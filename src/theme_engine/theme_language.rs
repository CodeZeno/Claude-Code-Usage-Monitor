/// What an expression gives, written the way the reference shows it: text in
/// quotes, numbers with up to four decimals.
pub fn describe_result(expression: &str, context: &DataContext) -> Result<String, String> {
    Ok(
        match super::theme_expression::evaluate_value(expression, context)? {
            ExpressionValue::Number(value) => describe_number(value),
            ExpressionValue::Text(text) => format!("\"{text}\""),
        },
    )
}

pub fn describe_number(value: f64) -> String {
    let text = format!("{value:.4}");
    let text = text.trim_end_matches('0').trim_end_matches('.');
    if text == "-0" {
        "0".into()
    } else {
        text.into()
    }
}

/// Whether `name` is a usage value: an owner, a window from
/// `PROVIDER_WINDOWS` and a field from `PROVIDER_FIELDS`.
pub fn is_usage_value(name: &str) -> bool {
    split_usage_owner(name).is_some_and(|(_, rest)| {
        let (window, field) = split_usage_window(rest);
        PROVIDER_WINDOWS.iter().any(|known| known.pattern == window)
            && PROVIDER_FIELDS.iter().any(|known| known.pattern == field)
    })
}

/// The value group describing a name that is not a usage value.
pub fn value_group(name: &str) -> Option<&'static ValueGroup> {
    VALUE_GROUPS.iter().find(|group| {
        if group.pattern.ends_with('.') {
            name.starts_with(group.pattern)
        } else {
            name == group.pattern
        }
    })
}

/// The candidate closest to `name` by edit distance, when it is close enough
/// to be a likely typo.
pub fn closest<'a>(name: &str, candidates: impl Iterator<Item = &'a str>) -> Option<&'a str> {
    let name = name.to_ascii_lowercase();
    let limit = (name.chars().count() / 3).max(1);
    candidates
        .map(|candidate| {
            (
                edit_distance(&name, &candidate.to_ascii_lowercase()),
                candidate,
            )
        })
        .filter(|(distance, _)| *distance <= limit)
        .min_by_key(|(distance, _)| *distance)
        .map(|(_, candidate)| candidate)
}

/// Edits (insert, delete, replace, swap neighbours) turning `left` into `right`.
fn edit_distance(left: &str, right: &str) -> usize {
    let left: Vec<char> = left.chars().collect();
    let right: Vec<char> = right.chars().collect();
    let width = right.len() + 1;
    let mut table = vec![0usize; (left.len() + 1) * width];
    for row in 0..=left.len() {
        for column in 0..=right.len() {
            table[row * width + column] = if row == 0 || column == 0 {
                row + column
            } else {
                let cost = usize::from(left[row - 1] != right[column - 1]);
                let mut best = (table[(row - 1) * width + column] + 1)
                    .min(table[row * width + column - 1] + 1)
                    .min(table[(row - 1) * width + column - 1] + cost);
                if row > 1
                    && column > 1
                    && left[row - 1] == right[column - 2]
                    && left[row - 2] == right[column - 1]
                {
                    best = best.min(table[(row - 2) * width + column - 2] + 1);
                }
                best
            };
        }
    }
    table[left.len() * width + right.len()]
}

