/// Fields set in a theme file that the theme format does not have, each with
/// the object it is on and the closest real field. Serde ignores unknown
/// fields, so without this a misspelt or invented field silently does nothing.
pub fn unknown_theme_fields(json: &serde_json::Value) -> Vec<String> {
    let mut problems = Vec::new();
    visit_theme_fields(json, &mut |owner, path, table, found| {
        if found.is_none() {
            // Suggest fields at the same level; paint keys and misplaced
            // fields have none, so they are compared with the whole table.
            let mut siblings: Vec<_> = table
                .iter()
                .map(|field| field.path)
                .filter(|candidate| parent_path(candidate) == parent_path(path))
                .collect();
            if siblings.is_empty() {
                siblings = table.iter().map(|field| field.path).collect();
            }
            problems.push(unknown_field_message(owner, path, siblings.into_iter()));
        }
    });
    problems
}

/// Calls `visit` with every field a theme file sets: the object id (or
/// `theme`), the field's path, the table it belongs in, and its entry there.
pub fn visit_theme_fields(json: &serde_json::Value, visit: &mut Visitor<'_>) {
    let Some(document) = json.as_object() else {
        return;
    };
    for (key, value) in document {
        let found = DOCUMENT_FIELDS.iter().find(|field| field.path == key);
        visit("theme", key, DOCUMENT_FIELDS, found);
        if key == "surfaces" {
            for surface in value.as_array().into_iter().flatten() {
                visit_object(surface, visit);
            }
        }
    }
}

/// The callback `visit_theme_fields` calls: owner, path, table and entry.
pub type Visitor<'a> =
    dyn FnMut(&str, &str, &'static [ThemeField], Option<&'static ThemeField>) + 'a;

fn visit_object(object: &serde_json::Value, visit: &mut Visitor<'_>) {
    let id = object
        .get("id")
        .and_then(serde_json::Value::as_str)
        .unwrap_or("(no id)");
    visit_object_fields(object, "", id, visit);
}

fn visit_object_fields(value: &serde_json::Value, prefix: &str, id: &str, visit: &mut Visitor<'_>) {
    let Some(map) = value.as_object() else {
        return;
    };
    for (key, child) in map {
        if key == "type" && prefix.ends_with(')') {
            continue;
        }
        let mut path = if prefix.is_empty() {
            key.clone()
        } else {
            format!("{prefix}.{key}")
        };
        if let Some(kind) = child.get("type").and_then(serde_json::Value::as_str) {
            path = format!("{path}({kind})");
        }
        // Older themes saved these; loading converts them.
        if matches!(
            path.as_str(),
            "content(image)" | "content(shape)" | "placement.layer"
        ) {
            continue;
        }
        let found = object_field(&path);
        visit(id, &path, OBJECT_FIELDS, found);
        match found.map(|field| field.kind) {
            Some(Objects) => {
                for object in child.as_array().into_iter().flatten() {
                    visit_object(object, visit);
                }
            }
            Some(Fill) => {
                for (key, _) in child.as_object().into_iter().flatten() {
                    let found = PAINT_FIELDS.iter().find(|field| field.path == key);
                    visit(id, &format!("{path}.{key}"), PAINT_FIELDS, found);
                }
            }
            Some(Group | Typed) => visit_object_fields(child, &path, id, visit),
            _ => {}
        }
    }
}

fn parent_path(path: &str) -> &str {
    path.rsplit_once('.').map_or("", |(parent, _)| parent)
}

fn unknown_field_message<'a>(
    owner: &str,
    path: &str,
    candidates: impl Iterator<Item = &'a str>,
) -> String {
    let last = |path: &'a str| path.rsplit('.').next().unwrap_or(path);
    let name = path.rsplit('.').next().unwrap_or(path);
    let candidates: Vec<_> = candidates.collect();
    let suggestion = closest(name, candidates.iter().map(|candidate| last(candidate)))
        .and_then(|best| candidates.iter().find(|candidate| last(candidate) == best))
        .map(|best| format!("; did you mean '{best}'?"))
        .unwrap_or_else(|| ".".into());
    format!(
        "{owner}: '{path}' is not a theme field{suggestion} Fields are listed in \
         {THEME_REFERENCE}#fields"
    )
}

