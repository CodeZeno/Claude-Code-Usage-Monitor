/// The owner (`claude`, `antigravity.gemini`, `active`, ...) a value name
/// starts with, and the rest after it.
pub fn split_usage_owner(name: &str) -> Option<(&str, &str)> {
    let owners = USAGE_OWNERS
        .iter()
        .map(|(owner, _)| *owner)
        .chain(PROVIDER_DESCRIPTORS.iter().map(|descriptor| descriptor.key));
    for owner in owners {
        if let Some(rest) = name
            .strip_prefix(owner)
            .and_then(|rest| rest.strip_prefix('.'))
        {
            return Some((&name[..owner.len()], rest));
        }
    }
    None
}

/// Splits the part after an owner into its window pattern and field:
/// `limits.weekly_scoped_fable.reset.unix` gives `("limits.<key>", "reset.unix")`.
pub fn split_usage_window(rest: &str) -> (String, &str) {
    let (window, field) = match rest.find(".reset.") {
        Some(index) => (&rest[..index], &rest[index + 1..]),
        None => rest.rsplit_once('.').unwrap_or(("", rest)),
    };
    let window = if let Some(key) = window.strip_prefix("limits.") {
        if key.is_empty() {
            window.to_string()
        } else {
            "limits.<key>".to_string()
        }
    } else if window.starts_with("model.") {
        "model.<model>".to_string()
    } else {
        window.to_string()
    };
    (window, field)
}

