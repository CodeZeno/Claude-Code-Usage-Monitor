/// Whether `format` (already lowercase, without `utc_`) is a timestamp format.
pub(super) fn is_timestamp_format(format: &str) -> bool {
    TEMPLATE_FORMATS.iter().any(|candidate| {
        candidate.kind == FormatKind::Timestamp
            && (candidate.code == format || candidate.aliases.contains(&format))
    })
}

/// The error for a template format the engine does not know, which would
/// otherwise render as a plain number.
pub(super) fn unknown_format_message(format: &str) -> Option<String> {
    let format = format.trim().to_ascii_lowercase();
    let number_pattern = format.chars().all(|c| matches!(c, '0' | '#' | '.' | ','));
    if format.is_empty() || number_pattern {
        return None;
    }
    let known = |format: &str| {
        TEMPLATE_FORMATS.iter().any(|candidate| {
            candidate.kind != FormatKind::UtcPrefix
                && (candidate.code == format || candidate.aliases.contains(&format))
        })
    };
    match format.strip_prefix("utc_") {
        Some(timestamp) if is_timestamp_format(timestamp) => return None,
        None if known(&format) => return None,
        _ => {}
    }
    let codes = TEMPLATE_FORMATS.iter().flat_map(|candidate| {
        std::iter::once(candidate.code).chain(candidate.aliases.iter().copied())
    });
    let suggestion = closest(&format, codes)
        .map(|best| format!("; did you mean '{best}'?"))
        .unwrap_or_else(|| ".".into());
    Some(format!(
        "Unknown format '{format}'{suggestion} Formats are listed in {THEME_REFERENCE}#formats"
    ))
}

