/// What a theme field holds.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FieldKind {
    /// A number expression, such as `canvas.width - 8`.
    Expression,
    /// An expression that counts as true when non-zero.
    Condition,
    /// Text with `{expression}` or `{expression:format}` tokens.
    Template,
    /// A mouse action script, such as `toggle("details", render)`.
    Actions,
    /// `#RRGGBB` or `#AARRGGBB`.
    Color,
    /// A colour object; see `PAINT_FIELDS`.
    Paint,
    /// One of the listed words.
    Choice(&'static [&'static str]),
    /// Literal text.
    Text,
    /// A whole number, not an expression.
    Integer,
    /// A list of objects with `OBJECT_FIELDS`.
    Objects,
    /// An object chosen by its `type`; the listed fields follow.
    Typed,
    /// A group of the fields listed after it.
    Group,
}

impl FieldKind {
    pub fn label(self) -> &'static str {
        match self {
            Self::Expression => "expression",
            Self::Condition => "condition",
            Self::Template => "template",
            Self::Actions => "actions",
            Self::Color => "colour",
            Self::Paint => "paint",
            Self::Choice(_) => "choice",
            Self::Text => "text",
            Self::Integer => "integer",
            Self::Objects => "objects",
            Self::Typed => "type",
            Self::Group => "group",
        }
    }
}

