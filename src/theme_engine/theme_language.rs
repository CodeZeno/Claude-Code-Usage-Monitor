//! The theme language in one place.
//!
//! Most theme fields are expressions rather than fixed values: `"width":
//! "canvas.width - 8"`, `"render": "claude.available && !data.has_error"`.
//! Text layers use templates such as `"{claude.session.percentage:0}%"`, and
//! mouse events run action scripts. The tables here define that language:
//!
//! - `call_function` only runs functions listed in `EXPRESSION_FUNCTIONS`,
//!   `parse_mouse_actions` only accepts actions in `MOUSE_ACTIONS`, and the
//!   timestamp formats come from `TEMPLATE_FORMATS`.
//! - `DOCUMENT_FIELDS`, `OBJECT_FIELDS` and `PAINT_FIELDS` name every field a
//!   theme can save and what it holds. Tests fail when a field is added to the
//!   theme types but not here, and `unknown_theme_fields` reports fields a
//!   theme file sets that do not exist.
//! - `VALUE_GROUPS`, `PROVIDER_WINDOWS` and `PROVIDER_FIELDS` describe the
//!   values expressions can read.
//!
//! Theme Studio's helper and `docs/theme-reference.md` (generated by
//! `theme_render::reference`) read the same tables, so whatever the engine
//! accepts is documented.

